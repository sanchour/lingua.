// Hand-checked meanings for the core languages' commonest words (5.1-3a, the user: "improve
// translation massively"). Two tables per language:
//  - VERBS: the English verb each common lemma is best read as, for formGloss to inflect ("querer"
//    is "want", not Wiktionary's first "to desire"; modal verbs as "can", "must").
//  - FIXES: forms whose meaning no rule gets right (function words, set phrases, homographs), the
//    most usual meaning first. They win over the pack and over the meaning picked from context.
// Loaded only when a text is opened (a dynamic import), so the app's first load doesn't carry it.

type Table = Record<string, string>;

const words = (s: string): Table => Object.fromEntries(s.trim().split(/\s*\n\s*/).map((line) => line.split(/\s*=\s*/) as [string, string]));

