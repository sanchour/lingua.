import { useLiveQuery } from 'dexie-react-hooks';
import { db } from '@/data/db';
import { UiText } from '@/design/i18n/UiText';
import { GeneratedLabel } from '@/features/generated/GeneratedLabel';

export function GeneratedReadingLabel({ id }: { id?: string }) {
  const row = useLiveQuery(async () => id ? await db.generated.get(id) : undefined, [id]);
  return id ? row ? <GeneratedLabel row={row} /> : <span className="text-xs text-ink-faint"><UiText source="Generated by Max" /></span> : null;
}
